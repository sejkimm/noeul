"""Generate the CSS color block, Neovim palette, Ghostty, zsh, pi and Claude Desktop themes from tokens.json."""

import json
from pathlib import Path

from oklch import hex_to_rgb, oklch_hex, rgb_to_oklch

PALETTE_DIR = Path(__file__).parent
ROOT = PALETTE_DIR.parent
MODES = ("light", "dark")
CSS_START, CSS_END = "/* palette:start (generated) */", "/* palette:end */"
# Claude Desktop role ramp: {stop: (lightness, share of the hue's chroma)}. Stop 300 is the dark text tone.
CLAUDE_DESKTOP_RAMP = {
    50: (0.97, 0.20),
    100: (0.945, 0.30),
    200: (0.85, 0.65),
    250: (0.80, 0.85),
    300: (0.745, 1.0),
    400: (0.61, 0.95),
    450: (0.575, 0.90),
    600: (0.46, 0.80),
    700: (0.36, 0.60),
    800: (0.225, 0.40),
    850: (0.195, 0.30),
}
# Raised surfaces 1 to 3: lightness added to bg1, the page.
CLAUDE_DESKTOP_RAISE = {"light": (0.008, 0.016, 0.016), "dark": (0.016, 0.032, 0.048)}
CLAUDE_DESKTOP_ROLES = {
    "danger": "red",
    "success": "green",
    "warning": "yellow",
    "pro": "magenta",
}


def load_palette() -> dict[str, dict]:
    """Resolve tokens.json into {mode: {name: hex}} plus {mode: {"ansi": [hex x16]}}."""
    tokens = json.loads((PALETTE_DIR / "tokens.json").read_text())
    palette = {}
    for mode in MODES:
        colors = dict(tokens["base"][mode])
        rule = tokens["hue_lightness"][mode]
        for name, hue in tokens["hues"].items():
            colors[name] = oklch_hex(rule["l"], hue["c"], hue["h"])
            colors[f"bright_{name}"] = oklch_hex(
                rule["bright_l"], hue["c"] * rule["bright_c"], hue["h"]
            )
        for name, tint in tokens["tints"].items():
            chroma = tint["c"][mode] if isinstance(tint["c"], dict) else tint["c"]
            colors[name] = oklch_hex(tint["l"][mode], chroma, tint["h"])
        colors["ansi"] = [colors[name] for name in tokens["ansi"]]
        palette[mode] = colors
    return palette


def css_block(palette: dict) -> str:
    light, dark = palette["light"], palette["dark"]
    names = [
        n
        for n in light
        if n != "ansi" and not n.startswith(("bright_", "diff_", "search", "panel_"))
    ]
    props = {n: "--" + n.replace("_", "-") + ":" for n in names}
    width = max(len(p) for p in props.values()) + 1
    lines = [f"  {props[n]:<{width}}light-dark({light[n]}, {dark[n]});" for n in names]
    return "\n".join([f"  {CSS_START}", *lines, f"  {CSS_END}"])


def write_css(palette: dict) -> None:
    path = ROOT / "web" / "noeul.css"
    text = path.read_text()
    start, end = text.index(CSS_START), text.index(CSS_END) + len(CSS_END)
    line_start = text.rindex("\n", 0, start) + 1
    path.write_text(text[:line_start] + css_block(palette) + text[end:])


def lua_table(colors: dict) -> str:
    lines = [f'    {n} = "{v}",' for n, v in colors.items() if n != "ansi"]
    ansi = ", ".join(f'"{v}"' for v in colors["ansi"])
    return "\n".join([*lines, f"    ansi = {{ {ansi} }},"])


def write_lua(palette: dict) -> None:
    body = "\n".join(
        f"  {mode} = {{\n{lua_table(palette[mode])}\n  }}," for mode in MODES
    )
    text = f"-- Generated by palette/build.py from palette/tokens.json. Do not edit.\nreturn {{\n{body}\n}}\n"
    (ROOT / "lua" / "noeul" / "palette.lua").write_text(text)


def write_ghostty(palette: dict) -> None:
    for mode in MODES:
        c = palette[mode]
        lines = [
            f"# Noeul {mode.title()}. Generated by palette/build.py from palette/tokens.json.",
            f"background = {c['bg1']}",
            f"foreground = {c['tx1']}",
            f"cursor-color = {c['ax3']}",
            f"cursor-text = {c['bg1']}",
            f"selection-background = {c['hl1']}",
            f"selection-foreground = {c['tx1']}",
            *(f"palette = {i}={color}" for i, color in enumerate(c["ansi"])),
        ]
        (ROOT / "ghostty" / f"noeul-{mode}").write_text("\n".join(lines) + "\n")


ZSH_PROMPT = r"""
autoload -Uz add-zsh-hook
add-zsh-hook precmd _noeul_accent

PROMPT=$'\n%F{$_noeul_ax1}%n@%m %F{$_noeul_caramel}%D{[%H:%M:%S]}%f %F{7}[%~]%f $(git_prompt_info)\n%F{$_noeul_caramel}-> %#%f '

ZSH_THEME_GIT_PROMPT_PREFIX='%F{$_noeul_brown}['
ZSH_THEME_GIT_PROMPT_SUFFIX="]%f"
ZSH_THEME_GIT_PROMPT_DIRTY=' %F{1}*%F{$_noeul_brown}'
ZSH_THEME_GIT_PROMPT_CLEAN=""
"""


def write_zsh(palette: dict) -> None:
    """An oh-my-zsh prompt in the crcandy layout. The path and the dirty mark use ANSI indices."""
    accents = {
        mode: " ".join(
            f"_noeul_{n}='{palette[mode][n]}'" for n in ("ax1", "caramel", "brown")
        )
        for mode in MODES
    }
    lines = [
        "# Noeul prompt for oh-my-zsh. Generated by palette/build.py from palette/tokens.json.",
        "# The accents are not in the 16 ANSI colors, so each prompt picks them from the",
        "# macOS appearance, the same switch Ghostty's light:/dark: theme follows.",
        "_noeul_accent() {",
        '  if [[ "$(defaults read -g AppleInterfaceStyle 2>/dev/null)" == Dark ]]; then',
        f"    {accents['dark']}",
        "  else",
        f"    {accents['light']}",
        "  fi",
        "}",
    ]
    path = ROOT / "zsh" / "noeul.zsh-theme"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines) + ZSH_PROMPT)


