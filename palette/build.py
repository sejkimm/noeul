def write_pi(palette: dict) -> None:
    for mode in MODES:
        c = palette[mode]
        theme = {
            "$schema": "https://pi.dev/schemas/theme.schema.json",
            "name": f"noeul-{mode}",
            "appearance": mode,
            "colors": pi_colors(c),
            "export": {"pageBg": c["bg1"], "cardBg": c["code_bg"], "infoBg": c["search"]},
        }
        path = ROOT / "pi" / f"noeul-{mode}.json"
        path.parent.mkdir(exist_ok=True)
        path.write_text(json.dumps(theme, indent=2) + "\n")


def claude_desktop_ramp(chroma: float, hue: float) -> dict[int, str]:
    return {
        stop: oklch_hex(l, chroma * share, hue)
        for stop, (l, share) in CLAUDE_DESKTOP_RAMP.items()
    }


def claude_desktop_surfaces(page: str, raise_by: tuple[float, ...]) -> dict[str, str]:
    l, chroma, hue = rgb_to_oklch(hex_to_rgb(page))
    return {
        f"surface-{i}": oklch_hex(l + step, chroma, hue)
        for i, step in enumerate(raise_by, start=1)
    }


def claude_desktop_definition(palette: dict) -> dict:
    """The input to Claude Desktop's makeColors: surface and text anchors per mode, one ramp per role."""
    hues = json.loads((PALETTE_DIR / "tokens.json").read_text())["hues"]
    _, chroma, hue = rgb_to_oklch(hex_to_rgb(palette["dark"]["ax1"]))
    roles = {"accent": {"stops": claude_desktop_ramp(chroma, hue)}}
    for role, name in CLAUDE_DESKTOP_ROLES.items():
        roles[role] = {"stops": claude_desktop_ramp(hues[name]["c"], hues[name]["h"])}
    roles["warning"]["fillShade"] = 300  # the stock 200 is too pale to see on cream
    modes = {
        mode: {
            "gray": {
                "anchors": {
                    "surface-0": c["bg1"],
                    **claude_desktop_surfaces(c["bg1"], CLAUDE_DESKTOP_RAISE[mode]),
                    "text-primary": c["tx1"],
                    "text-secondary": c["tx2"],
                    "text-muted": c["tx3"],
                }
            },
            "git": {
                "added": c["green"],
                "removed": c["red"],
                "modified": c["yellow"],
                "merged": c["magenta"],
                "closed": c["red"],
                "conflicting": c["yellow"],
                "draft": c["tx2"],
            },
        }
        for mode, c in palette.items()
    }
    return {"label": "Noeul", "roles": roles, **modes}


def write_claude_desktop(palette: dict) -> None:
    body = json.dumps(claude_desktop_definition(palette), indent=2)
    text = f"// Generated by palette/build.py from palette/tokens.json. Do not edit.\nexport const PALETTE = {body}\n"
    (ROOT / "claude-desktop" / "hooks" / "palette.ts").write_text(text)


def main() -> None:
    palette = load_palette()
    write_css(palette)
    write_lua(palette)
    write_ghostty(palette)
    write_zsh(palette)
    write_pi(palette)
    write_claude_desktop(palette)
    print(
        "wrote web/noeul.css, lua/noeul/palette.lua, ghostty/noeul-{light,dark}, zsh/noeul.zsh-theme, pi/noeul-{light,dark}.json, claude-desktop/hooks/palette.ts"
    )


if __name__ == "__main__":
    main()
