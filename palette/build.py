"""Generate the CSS color block, Neovim palette, and Ghostty themes from tokens.json."""

import json
from pathlib import Path

from oklch import oklch_hex

PALETTE_DIR = Path(__file__).parent
ROOT = PALETTE_DIR.parent
MODES = ("light", "dark")
CSS_START, CSS_END = "/* palette:start (generated) */", "/* palette:end */"


def load_palette() -> dict[str, dict]:
    """Resolve tokens.json into {mode: {name: hex}} plus {mode: {"ansi": [hex x16]}}."""
    tokens = json.loads((PALETTE_DIR / "tokens.json").read_text())
    palette = {}
    for mode in MODES:
        colors = dict(tokens["base"][mode])
        rule = tokens["hue_lightness"][mode]
        for name, hue in tokens["hues"].items():
            colors[name] = oklch_hex(rule["l"], hue["c"], hue["h"])
            colors[f"bright_{name}"] = oklch_hex(
                rule["bright_l"], hue["c"] * rule["bright_c"], hue["h"]
            )
        for name, tint in tokens["tints"].items():
            colors[name] = oklch_hex(tint["l"][mode], tint["c"], tint["h"])
        colors["ansi"] = [colors[name] for name in tokens["ansi"]]
        palette[mode] = colors
    return palette


def css_block(palette: dict) -> str:
    light, dark = palette["light"], palette["dark"]
    names = [
        n
        for n in light
        if n != "ansi" and not n.startswith(("bright_", "diff_", "search"))
    ]
    props = {n: "--" + n.replace("_", "-") + ":" for n in names}
    width = max(len(p) for p in props.values()) + 1
    lines = [f"  {props[n]:<{width}}light-dark({light[n]}, {dark[n]});" for n in names]
    return "\n".join([f"  {CSS_START}", *lines, f"  {CSS_END}"])


def write_css(palette: dict) -> None:
    path = ROOT / "web" / "noeul.css"
    text = path.read_text()
    start, end = text.index(CSS_START), text.index(CSS_END) + len(CSS_END)
    line_start = text.rindex("\n", 0, start) + 1
    path.write_text(text[:line_start] + css_block(palette) + text[end:])


def lua_table(colors: dict) -> str:
    lines = [f'    {n} = "{v}",' for n, v in colors.items() if n != "ansi"]
    ansi = ", ".join(f'"{v}"' for v in colors["ansi"])
    return "\n".join([*lines, f"    ansi = {{ {ansi} }},"])


def write_lua(palette: dict) -> None:
    body = "\n".join(
        f"  {mode} = {{\n{lua_table(palette[mode])}\n  }}," for mode in MODES
    )
    text = f"-- Generated by palette/build.py from palette/tokens.json. Do not edit.\nreturn {{\n{body}\n}}\n"
    (ROOT / "lua" / "noeul" / "palette.lua").write_text(text)


def write_ghostty(palette: dict) -> None:
    for mode in MODES:
        c = palette[mode]
        lines = [
            f"# Noeul {mode.title()}. Generated by palette/build.py from palette/tokens.json.",
            f"background = {c['bg1']}",
            f"foreground = {c['tx1']}",
            f"cursor-color = {c['ax3']}",
            f"cursor-text = {c['bg1']}",
            f"selection-background = {c['hl1']}",
            f"selection-foreground = {c['tx1']}",
            *(f"palette = {i}={color}" for i, color in enumerate(c["ansi"])),
        ]
        (ROOT / "ghostty" / f"noeul-{mode}").write_text("\n".join(lines) + "\n")


def main() -> None:
    palette = load_palette()
    write_css(palette)
    write_lua(palette)
    write_ghostty(palette)
    print(
        "wrote web/noeul.css, lua/noeul/palette.lua, ghostty/noeul-light, ghostty/noeul-dark"
    )


if __name__ == "__main__":
    main()
